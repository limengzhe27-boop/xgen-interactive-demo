import type { StoryOutlineBeat, WorldDefinition } from '@/lib/ai-contracts';

export type CreatorDetailBaseline = {
  roles: { name: string; identity: string; personality: string; appearance: string; relationship: string; goal?: string; cardHook?: string }[];
  outline: StoryOutlineBeat[];
};

export function preserveCreatorDetails(base: WorldDefinition, edited: WorldDefinition, before: CreatorDetailBaseline, after: CreatorDetailBaseline): WorldDefinition {
  const locations = base.locations.map((location) => ({ ...location, connectedLocationIds: [...location.connectedLocationIds] }));
  after.outline.forEach((beat, index) => {
    const previous = before.outline[index];
    if (!previous || previous.location === beat.location || !beat.location.trim()) return;
    const original = base.locations.find((location) => location.name === previous.location)
      ?? (index === 0 ? base.locations.find((location) => location.id === base.openingScene.locationId) : undefined);
    const location = locations.find((item) => item.id === original?.id);
    if (location) location.name = beat.location.trim(); // Rename, never replace the graph or its stable IDs.
    else if (!locations.some((item) => item.name === beat.location.trim())) {
      let id = `creator-added-location-${index}`;
      while (locations.some((item) => item.id === id)) id += '-new';
      locations.push({ id, name: beat.location.trim(), description: beat.objective, connectedLocationIds: [] });
    }
  });
  const premiseChanged = base.premise.trim() !== edited.premise.trim();
  const openingEdited = before.outline[0] && after.outline[0]
    && (before.outline[0].objective !== after.outline[0].objective || before.outline[0].turningPoint !== after.outline[0].turningPoint);
  const narrative = openingEdited
    ? `${edited.premise}\n\n${after.outline[0].objective}。${after.outline[0].turningPoint}`
    : premiseChanged ? edited.premise : base.openingScene.narrative;
  const characters = base.characters.map((character, index) => {
    const previous = before.roles[index]; const next = after.roles[index];
    if (!previous || !next) return character;
    return { ...character,
      name: next.name !== previous.name ? next.name : character.name,
      cardHook: next.cardHook !== previous.cardHook ? next.cardHook : character.cardHook,
      identity: next.identity !== previous.identity ? next.identity : character.identity,
      persona: next.personality !== previous.personality ? next.personality : character.persona,
      goal: next.goal !== previous.goal ? (next.goal?.trim() || edited.characters[index]?.goal || character.goal) : character.goal,
      publicBackground: next.relationship !== previous.relationship ? next.relationship : character.publicBackground,
      imagePrompt: next.appearance !== previous.appearance ? next.appearance : character.imagePrompt,
    };
  });
  return { ...edited, storyHook: base.storyHook, locations, characters, coreEvent: premiseChanged ? edited.premise : base.coreEvent,
    openingScene: { ...base.openingScene, narrative },
    difficultyConstraints: edited.difficultyConstraints.map((item) => base.difficultyConstraints.find((original) => original.description === item.description
      && edited.tasks.some((task) => task.id === original.blocksTaskId)) ?? item),
    scheduledEvents: edited.scheduledEvents.map((item) => base.scheduledEvents.find((original) => original.title === item.title && original.trigger === item.trigger && original.effect === item.effect) ?? item),
  };
}

// The simple editor projects one goal and one ending per outcome. Publishing that
// projection must not erase the richer, role-scoped graph generated by the agent.
export function preserveCreatorFramework(base: WorldDefinition, edited: WorldDefinition, explicitAssignments: string[] = []): WorldDefinition {
  const rolePlan = edited.goals.some((goal) => goal.scope === 'role');
  const taskIds = new Set(edited.tasks.map((task) => task.id));
  const tasks = edited.tasks.map((task) => ({ ...task,
    assignedRoleIds: explicitAssignments.includes(task.id) ? task.assignedRoleIds : base.tasks.find((original) => original.id === task.id)?.assignedRoleIds ?? task.assignedRoleIds,
  }));
  const displayGoal = base.goals.find((goal) => goal.scope === 'world') ?? base.goals[0];
  const goals = base.goals.map((goal) => ({ ...goal,
    ...(goal.id === displayGoal?.id ? { title: edited.goals[0]?.title ?? goal.title } : {}),
    requiredTaskIds: goal.requiredTaskIds.filter((id) => taskIds.has(id)),
  }));
  // Newly added tasks belong to the editor's displayed goal, not every NPC goal.
  const addedMain = tasks.filter((task) => task.kind === 'main' && !base.tasks.some((old) => old.id === task.id)).map((task) => task.id);
  const displayed = goals.find((goal) => goal.id === displayGoal?.id);
  if (displayed) displayed.requiredTaskIds.push(...addedMain);
  const endingConditions = (['success', 'failure'] as const).flatMap((outcome) => {
    const originals = base.endingConditions.filter((ending) => (ending.outcome ?? 'success') === outcome);
    const replacement = edited.endingConditions.find((ending) => (ending.outcome ?? 'success') === outcome);
    if (!replacement) return []; // Explicitly cleared in the editor.
    if (!originals.length) return [replacement];
    return originals.map((ending, index) => {
      const changed = index === 0 && (!rolePlan || outcome === 'failure') && ending.description !== replacement.description;
      return { ...ending,
        description: changed ? replacement.description : ending.description,
        requiredTaskIds: [...ending.requiredTaskIds.filter((id) => taskIds.has(id)),
          ...(outcome === 'success' && index === 0 ? addedMain : [])],
        requiredFailedTaskIds: ending.requiredFailedTaskIds?.filter((id) => taskIds.has(id)),
        // Edited end conditions become explicit facts instead of retaining stale labels.
        requiredFacts: changed ? [replacement.description] : ending.requiredFacts,
      };
    });
  });
  const mergedGoals = rolePlan ? [
    ...goals.map((goal) => { const replacement = edited.goals.find((item) => item.scope === goal.scope && item.roleId === goal.roleId); return replacement ? { ...goal, title: replacement.title, requiredTaskIds: replacement.requiredTaskIds } : goal; }),
    ...edited.goals.filter((goal) => !goals.some((item) => item.scope === goal.scope && item.roleId === goal.roleId)),
  ] : goals.length ? goals : edited.goals;
  return { ...edited, tasks, goals: mergedGoals,
    // Rich AI endings retain facts, failure paths and IDs.
    endingConditions: rolePlan && base.endingConditions.every((ending) => ending.id.startsWith('creator-')) ? edited.endingConditions : endingConditions };
}
